#!/usr/bin/env node
/**
 * gen-codex-routers — generate the Codex `.agents/skills/loop-*` router surface
 * for a bound repo.
 *
 * Codex discovers skills only from a repo's `.agents/skills/<name>/SKILL.md`
 * (it must not read `~/.claude/`), so each plugin skill gets a thin generated
 * router there. Routers bake NO paths: the canonical body location is read
 * from `.loop/config.json` (`codex.plugin_root`) at USE time, which makes
 * generation a pure function of the plugin's skill list — byte-deterministic,
 * and never stale on plugin update.
 *
 * CLI: gen-codex-routers.js --json [--repo <root>] [--check]
 *   --check verifies the committed routers match the generated bytes (no
 *   writes) — the preflight determinism gate uses it.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const EXIT_CODES = Object.freeze({ success: 0, refusal: 1, usage: 2 });
const SKILLS_DIR = path.resolve(__dirname, '..', 'skills');
const ROUTER_PREFIX = 'loop-';

function parseFrontmatter(body) {
  const match = body.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) return null;
  const out = {};
  for (const line of match[1].split('\n')) {
    const idx = line.indexOf(':');
    if (idx < 0) continue;
    out[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  return out;
}

function listPluginSkills(skillsDir = SKILLS_DIR) {
  const names = fs.readdirSync(skillsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  return names.map((name) => {
    const bodyPath = path.join(skillsDir, name, 'SKILL.md');
    const body = fs.readFileSync(bodyPath, 'utf8');
    const fm = parseFrontmatter(body);
    if (!fm || !fm.name || !fm.description) {
      throw new Error(`plugin skill ${name} has no name/description frontmatter`);
    }
    if (fm.name !== name) throw new Error(`plugin skill dir ${name} declares mismatched name ${fm.name}`);
    return { name, description: fm.description };
  });
}

function titleCase(name) {
  return name.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

function routerFiles(skill) {
  const routerName = `${ROUTER_PREFIX}${skill.name}`;
  const skillMd = [
    '---',
    `name: ${routerName}`,
    `description: ${skill.description}`,
    '---',
    '',
    `# ${routerName} (generated router)`,
    '',
    'GENERATED by the sauce loop plugin — do not edit; regenerate via /loop:init (gen-codex-routers.js).',
    '',
    '1. Read `.loop/config.json` at the repo root. `codex.plugin_root` is the directory holding the canonical loop skill bodies (single source of truth shared with the Claude plugin surface).',
    `2. Read \`<codex.plugin_root>/skills/${skill.name}/SKILL.md\` and follow it exactly. Where that body references \`\${CLAUDE_PLUGIN_ROOT}\`, substitute \`<codex.plugin_root>\`.`,
    '3. The repo binding (vault/board/policy) is `.loop/config.json`; the body\'s resolver commands read it.',
    '',
    'If `codex.plugin_root` is unset or the body is missing, stop and report the exact path — never improvise the procedure.',
    '',
  ].join('\n');
  const shortDescription = `Loop ${skill.name} via the shared sauce loop plugin body`;
  const openaiYaml = [
    'interface:',
    `  display_name: "Loop ${titleCase(skill.name)}"`,
    `  short_description: "${shortDescription}"`,
    `  default_prompt: "Use $${routerName} — follow .agents/skills/${routerName}/SKILL.md."`,
    '',
  ].join('\n');
  return {
    [`${routerName}/SKILL.md`]: skillMd,
    [`${routerName}/agents/openai.yaml`]: openaiYaml,
  };
}

function generate(skillsDir = SKILLS_DIR) {
  const files = {};
  for (const skill of listPluginSkills(skillsDir)) Object.assign(files, routerFiles(skill));
  return files;
}

function main(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i];
    if (!token.startsWith('--')) continue;
    const key = token.slice(2);
    const value = argv[i + 1];
    if (value && !value.startsWith('--')) { args[key] = value; i++; } else args[key] = true;
  }
  const action = args.check === true ? 'gen-codex-routers-check' : 'gen-codex-routers';
  const emit = (payload, exitCode) => {
    process.stdout.write(JSON.stringify(payload, null, 2) + '\n');
    process.exit(exitCode);
  };
  if (args.json !== true) {
    emit({ action, ok: false, no_op: false, code: 'json_required', message: 'gen-codex-routers requires --json' }, EXIT_CODES.usage);
  }
  const repoRoot = path.resolve(args.repo || process.cwd());
  if (!fs.existsSync(path.join(repoRoot, '.loop', 'config.json'))) {
    emit({ action, ok: false, no_op: false, refusals: [{ code: 'config_missing', message: `no .loop/config.json at ${repoRoot} — run /loop:init first` }] }, EXIT_CODES.refusal);
  }
  const files = generate();
  const agentsRoot = path.join(repoRoot, '.agents', 'skills');

  if (args.check === true) {
    const mismatches = [];
    for (const [rel, content] of Object.entries(files)) {
      const target = path.join(agentsRoot, rel);
      if (!fs.existsSync(target)) mismatches.push({ file: rel, problem: 'missing' });
      else if (fs.readFileSync(target, 'utf8') !== content) mismatches.push({ file: rel, problem: 'differs' });
    }
    if (mismatches.length) {
      emit({ action, ok: false, no_op: false, refusals: [{ code: 'routers_stale', message: 'committed routers do not match generated bytes — rerun gen-codex-routers.js', mismatches }] }, EXIT_CODES.refusal);
    }
    emit({ action, ok: true, no_op: true, checked: Object.keys(files).length }, EXIT_CODES.success);
  }

  const written = [];
  for (const [rel, content] of Object.entries(files)) {
    const target = path.join(agentsRoot, rel);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    const before = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (before !== content) { fs.writeFileSync(target, content); written.push(rel); }
  }
  emit({ action, ok: true, no_op: written.length === 0, written }, EXIT_CODES.success);
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { generate, listPluginSkills, routerFiles, parseFrontmatter, ROUTER_PREFIX, SKILLS_DIR };
